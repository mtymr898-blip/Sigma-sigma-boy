export function buildOtpMessage(code, ttlSec) {
  const mins = Math.max(1, Math.round(Number(ttlSec || 120) / 60));
  return `🔐 کد ورود QAIRO\n\n${code}\n\nاین کد تا ${mins} دقیقه معتبر است.\nاگر خودتان درخواست نداده‌اید، آن را نادیده بگیرید و با کسی به اشتراک نگذارید.`;
}
